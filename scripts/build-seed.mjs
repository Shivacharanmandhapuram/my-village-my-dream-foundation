// Turns db/seed-source.txt into db/seed.sql.
// Inserts use "on conflict do nothing", so re-running never overwrites edits made in the CMS.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = readFileSync(`${root}db/seed-source.txt`, 'utf8');

const CATEGORY_EMOJI = {
  'dairy-products': '🥛',
  'grains-pulses-and-staples': '🌾',
  'fresh-produce': '🥬',
  'home-made-foods-and-spices': '🫙',
  'clothing-tailoring-and-crafts': '🧵',
  services: '🔧',
};
const PRODUCT_EMOJI = {
  milk: '🥛', curd: '🥣', butter: '🧈', ghee: '🫙',
  wheat: '🌾', 'wheat-flour': '🍞', rice: '🍚', jowar: '🌽', chickpeas: '🫘', 'pigeon-peas': '🫘',
  soybeans: '🫛', 'mung-beans': '🫛', pulses: '🥣',
  vegetables: '🥬',
  papad: '🫓', chips: '🥔', chivda: '🥜', cake: '🎂', turmeric: '🟡', 'red-chilli-powder': '🌶️', fenugreek: '🌿',
  clothes: '👗', tailoring: '🧵', 'blouse-stitching': '🪡', 'deity-idols': '🪔',
  'vehicle-repair': '🔧',
};

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const isLatin = (s) => /[a-z]/i.test(s);
const splitPair = (s) => {
  const parts = s.split(' / ').map((p) => p.trim());
  return { en: parts.filter(isLatin).join(' / '), mr: parts.filter((p) => !isLatin(p)).join(' / ') };
};

const categories = [], products = [], sellers = new Map(), listings = [];
let cat = null, prod = null;

for (const raw of src.split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('#') && !line.startsWith('##')) continue;
  if (line.startsWith('### ')) {
    const { en, mr } = splitPair(line.slice(4));
    prod = { id: slug(en), category_id: cat.id, name_en: en, name_mr: mr, emoji: PRODUCT_EMOJI[slug(en)] ?? cat.emoji, sort: products.length * 10 };
    products.push(prod);
  } else if (line.startsWith('## ')) {
    const { en, mr } = splitPair(line.slice(3));
    cat = { id: slug(en), name_en: en, name_mr: mr, emoji: CATEGORY_EMOJI[slug(en)] ?? '🛒', sort: categories.length * 10 };
    categories.push(cat);
  } else if (line.startsWith('- ')) {
    const [names, phonePart] = line.slice(2).split(' — ');
    const { en, mr } = splitPair(names);
    const phones = phonePart.split('/').map((p) => p.replace(/\D/g, '')).filter(Boolean);
    const id = slug(en);
    const prev = sellers.get(id);
    if (prev && prev.phones.join() !== phones.join()) throw new Error(`Phone mismatch for ${en}`);
    sellers.set(id, { id, name_en: en, name_mr: mr, phones });
    const position = listings.filter((l) => l.product_id === prod.id).length * 10;
    listings.push({ seller_id: id, product_id: prod.id, position });
  }
}

const q = (v) => (v === null ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const insert = (table, cols, rows, fmt = (r) => cols.map((c) => q(r[c])).join(', ')) =>
  `insert into ${table} (${cols.join(', ')}) values\n${rows.map((r) => `  (${fmt(r)})`).join(',\n')}\non conflict do nothing;\n`;

const sql = [
  `-- Generated by scripts/build-seed.mjs from db/seed-source.txt — do not edit by hand.`,
  `-- ${categories.length} categories, ${products.length} products, ${sellers.size} villagers, ${listings.length} listings.\n`,
  insert('categories', ['id', 'name_en', 'name_mr', 'emoji', 'sort'], categories),
  insert('products', ['id', 'category_id', 'name_en', 'name_mr', 'emoji', 'sort'], products),
  insert('sellers', ['id', 'name_en', 'name_mr', 'phones'], [...sellers.values()],
    (r) => [q(r.id), q(r.name_en), q(r.name_mr), arr(r.phones)].join(', ')),
  insert('listings', ['seller_id', 'product_id', 'position'], listings),
].join('\n');

writeFileSync(`${root}db/seed.sql`, sql);
console.log(`db/seed.sql: ${categories.length} categories, ${products.length} products, ${sellers.size} villagers, ${listings.length} listings`);
